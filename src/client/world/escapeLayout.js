/**
 * 로봇이 도는 **도로** — `[col0, row0, col1, row1]` 사각형(양 끝 포함)의 합집합을
 * walk 마스크와 교집합해서 쓴다 (makeRoamBlocked).
 *
 * walk 마스크만으로 배회시키면 안 되는 이유: 마스크는 **플레이어용 관대한 판정**이라
 * 길이 아닌 곳도 열려 있다 — 왼쪽 웅덩이 안 바위섬(13~20열 15~22행), 남서쪽 바위 언덕
 * 꼭대기(6~11열 30~36행), 웅덩이 테두리 흙둔덕 띠(6행·37행 등). 기획자가 벽만 빨강으로
 * 칠한 판이라 "벽은 아니지만 길도 아닌" 자리가 다 열렸고, 플레이어가 반 칸 걸치는 건
 * 문제가 아니지만 로봇이 무작위 목적지로 거길 **찍고 올라서면** 벽을 타는 것으로 보인다
 * (2026-08-07 제보). 그래서 배회만 이 사각형으로 제한한다 — 시야·충돌은 그대로 마스크다.
 *
 * 좌표는 walk 마스크의 열린 구간에서 골랐다(포장길 띠만). 교집합으로 쓰므로 사각형이
 * 마스크보다 한두 칸 넉넉해도 마스크가 잘라 준다. 홈 셋에서 도로 941칸 전부에 닿는 것
 * 확인 — 바꾸면 node scripts/check-escape-spawn.js 로 다시 재라.
 */
export const ROAM_ROADS = [
  [1, 1, 52, 5], // 북쪽 광장 (에바 구역 포함)
  [1, 23, 52, 24], // 가운데 가로 복도
  [1, 38, 52, 40], // 남쪽 복도
  [1, 1, 5, 40], // 서쪽 세로 복도
  [48, 1, 52, 40], // 동쪽 세로 복도
  [24, 6, 28, 18], // 가운데 위 통로 — 19행 파이프에서 끊기는 막다른 골목
  [24, 20, 27, 22], // 가운데 위 통로의 남쪽 토막 (가로 복도 ~ 파이프)
  [23, 27, 28, 37], // 가운데 아래 통로 — 남쪽 복도에서만 닿는다
  [41, 32, 52, 36], // 남동쪽 빈터
];

/**
 * 배회용 막힘 판정 — 마스크가 막거나 **도로 밖**이면 막힌 것으로 본다.
 *
 * Sentry 의 길찾기에만 넘긴다. 시야(rayDistance·hasLineOfSight)에 넘기면 안 된다 —
 * 시야까지 도로에 막히면 로봇이 웅덩이 테두리 너머를 못 보게 되어, 화면에 그려지는
 * 콘과 실제 판정이 어긋난다.
 *
 * @param {(col: number, row: number) => boolean} isBlocked 충돌이 보는 벽 (los.makeBlockedLookup)
 */
export const makeRoamBlocked = (isBlocked) => (col, row) => {
  if (isBlocked(col, row)) return true;
  return !ROAM_ROADS.some(([c0, r0, c1, r1]) => col >= c0 && col <= c1 && row >= r0 && row <= r1);
};

