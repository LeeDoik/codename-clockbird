/**
 * 인물이 화면에 보일 높이(월드 px). escape.json 의 `charHeight` 로 구워져 씬과
 * worldParts(발밑 판정 크기)가 같이 읽는다 — worldParts.DEFAULT_CHAR_HEIGHT 참고.
 */
export const CHAR_HEIGHT = 88;
/**
 * 카메라 배율.
 *
 * 화면에서의 인물 크기는 charHeight × cameraZoom 이다. 88×1 은 네 맵 중 혼자 작았다 —
 * 본부 160 · 저택 168 · 거리 128 사이에서 수로만 88 이라, 같은 인물이 이 스테이지에서만
 * 절반 크기로 섰다. (계획서 §1 의 "100~130" 은 08-02 판 기준이고, 그 뒤 본부와 저택이
 * 그 구간 위로 올라갔다.)
 *
 * 2 인 이유는 둘이다. 하나는 **정수**여야 픽셀 아트가 뭉개지지 않는다는 것
 * (worldParts.WORLD_ZOOM 주석). 다른 하나는 1 에서 맵이 화면보다 좁았다는 것이다 —
 * 54칸 × 32px = 1728px 인데 캔버스가 1920px 이라 좌우에 96px 씩 빈 띠가 남았다.
 * 1.12 배부터 그 띠가 사라진다.
 *
 * 시야가 좁아져도 불공평해지지 않는다: 콘 사거리가 220px 인데 줌 2 의 화면 반높이가
 * 270px 이라 **나를 볼 수 있는 로봇은 언제나 화면 안에 있다**.
 */
export const CAMERA_ZOOM = 2;

/** 타일 좌표 → 픽셀 중심 */
export const at = (col, row) => ({ x: col * TILE + TILE / 2, y: row * TILE + TILE / 2 });

